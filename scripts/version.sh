#!/usr/bin/env bash
#
# version.sh - print the version of the repository.
#
# The version is computed by versioner (see tools/versioner and
# .versioner.json), so the version of a build and the version of a release
# can never drift apart.
#
# Usage:
#   scripts/version.sh                 # prints "VERSION=<v>" and "TAG=<t>"
#   scripts/version.sh --format shell  # prints "export VERSION=..." lines
#   scripts/version.sh --format json   # prints the raw versioner json
#   scripts/version.sh --write         # also materialise .version/Version.hpp
#                                      # and .version/Version.txt
#
# Environment:
#   VERSIONER_BIN        Path to the versioner binary (default: via scripts/entry.sh).
#   VERSIONER_REPO_DIR   Repository to inspect (default: the repository root).
#   VERSION_DIR          Output directory for --write (default: .version).

set -euo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck disable=SC1091
source "$SCRIPT_DIR/entry.sh"

FORMAT="text"
WRITE=0
while [[ $# -gt 0 ]]; do
  case "$1" in
  --format)
    [[ $# -ge 2 ]] || {
      log ERROR "--format requires a value"
      exit 2
    }
    FORMAT="$2"
    shift 2
    ;;
  --format=*)
    FORMAT="${1#--format=}"
    shift
    ;;
  --write)
    WRITE=1
    shift
    ;;
  --help | -h)
    cat <<'EOF'
Usage: scripts/version.sh [--format text|shell|json] [--write]

Print the version of the repository computed by versioner.

  text   VERSION=<version> and TAG=<tag> lines (default)
  shell  export VERSION=... and export TAG=... lines
  json   the raw json document produced by versioner
  --write  additionally materialise .version/Version.hpp and
           .version/Version.txt (used by the C++ build)
EOF
    exit 0
    ;;
  *)
    log ERROR "unknown argument: $1"
    exit 2
    ;;
  esac
done

REPO_DIR="${VERSIONER_REPO_DIR:-${REPO_ROOT_DIR:-$SCRIPT_DIR/..}}"
REPO_DIR="$(cd -- "$REPO_DIR" && pwd)"

if [[ -z "${VERSIONER_BIN:-}" || ! -x "${VERSIONER_BIN:-}" ]]; then
  log ERROR "no versioner binary found (run tools/versioner/update.sh or set VERSIONER_BIN)"
  exit 1
fi

if [[ "$FORMAT" == "json" ]]; then
  "$VERSIONER_BIN" --repo-dir "$REPO_DIR" --quiet --format json
  exit 0
fi

OUTPUT="$("$VERSIONER_BIN" --repo-dir "$REPO_DIR" --quiet)"

VERSION="$(printf '%s\n' "$OUTPUT" | sed -n 's/^VERSION=//p' | tail -1)"
TAG="$(printf '%s\n' "$OUTPUT" | sed -n 's/^TAG=//p' | tail -1)"

[[ -n "$VERSION" ]] || {
  log ERROR "could not parse VERSION from the versioner output"
  exit 1
}
[[ -n "$TAG" ]] || {
  log ERROR "could not parse TAG from the versioner output"
  exit 1
}

case "$FORMAT" in
text)
  printf 'VERSION=%s\n' "$VERSION"
  printf 'TAG=%s\n' "$TAG"
  ;;
shell)
  printf 'export VERSION=%s\n' "$VERSION"
  printf 'export TAG=%s\n' "$TAG"
  ;;
*)
  log ERROR "unknown format: $FORMAT (expected text, shell or json)"
  exit 2
  ;;
esac

if [[ "$WRITE" -eq 1 ]]; then
  IFS='.' read -ra PARTS <<<"$VERSION"
  if [[ ${#PARTS[@]} -ne 5 ]]; then
    log ERROR "cannot --write: version '$VERSION' is not a five-part <branch>.<major>.<minor>.<revision>.<patch> version"
    exit 1
  fi
  for part in "${PARTS[@]}"; do
    if ! [[ "$part" =~ ^[0-9]+$ ]]; then
      log ERROR "cannot --write: version component '$part' is not numeric (from '$VERSION')"
      exit 1
    fi
  done
  VERSION_DIR="${VERSION_DIR:-.version}"
  case "$VERSION_DIR" in
  /*) VERSION_DIR_ABS="$VERSION_DIR" ;;
  *) VERSION_DIR_ABS="$REPO_DIR/${VERSION_DIR#./}" ;;
  esac
  mkdir -p "$VERSION_DIR_ABS"
  VERSION_HPP="$VERSION_DIR_ABS/Version.hpp"
  VERSION_TXT="$VERSION_DIR_ABS/Version.txt"
  # Autogenerated file, do not edit!
  cat >"$VERSION_HPP" <<EOF
// Autogenerated file, do not edit!
#pragma once
#include <stdint.h>

struct Version {
    static constexpr uint32_t branch = ${PARTS[0]};
    static constexpr uint32_t major = ${PARTS[1]};
    static constexpr uint32_t minor = ${PARTS[2]};
    static constexpr uint32_t revision = ${PARTS[3]};
    static constexpr uint32_t patch = ${PARTS[4]};
};
EOF
  printf '%s\n' "$VERSION" >"$VERSION_TXT"
  log INFO "wrote $VERSION_HPP and $VERSION_TXT" >&2
fi
